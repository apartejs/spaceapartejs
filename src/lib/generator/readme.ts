/**
 * The Hub validates the card gradient against a fixed palette and refuses to build
 * on anything else, so an unknown colour falls back rather than breaking the Space.
 */
const HF_COLOURS = [
  'red',
  'yellow',
  'green',
  'blue',
  'indigo',
  'purple',
  'pink',
  'gray',
] as const;

function safeColour(value: string, fallback: string): string {
  const colour = value.trim().toLowerCase();
  return (HF_COLOURS as readonly string[]).includes(colour) ? colour : fallback;
}

/**
 * One emoji, or the default.
 *
 * `emoji:` is a card field like the colours, and it was the only one taking user
 * input on trust — a sentence, a newline or a stray `"` would land in the front
 * matter and the card would carry whatever was typed. So: one pictographic
 * grapheme (a base, with the variation selectors, skin-tone modifiers and
 * ZWJ-joined parts that make up a single glyph), nothing else.
 */
const EMOJI_GRAPHEME =
  /^\p{Extended_Pictographic}(?:[\uFE0E\uFE0F\u{1F3FB}-\u{1F3FF}]|\u200D\p{Extended_Pictographic}[\uFE0E\uFE0F\u{1F3FB}-\u{1F3FF}]?)*$/u;

/** A four-person family with skin tones is 19 UTF-16 units; nothing legitimate is longer. */
const EMOJI_MAX_LENGTH = 24;

export function safeEmoji(value: string): string {
  const emoji = value.trim();
  if (!emoji || emoji.length > EMOJI_MAX_LENGTH) return DEFAULT_CONFIG.emoji;
  return EMOJI_GRAPHEME.test(emoji) ? emoji : DEFAULT_CONFIG.emoji;
}

/**
 * A double-quoted YAML scalar.
 *
 * Quoted rather than bare because a title is user input: a leading `#`, a `: `, a
 * `[` or a stray newline all mean something to a YAML parser and none of them mean
 * it here. Inside double quotes only `\` and `"` need escaping, and control
 * characters have to go — a newline in a title would end the value.
 */
export function yamlString(value: string): string {
  const escaped = value
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/[\u0000-\u001f\u007f]/g, ' ')
    .trim();
  return `"${escaped}"`;
}

/**
 * A user value that is about to sit inside a Markdown code span.
 *
 * Three things end a span early, and all three are ordinary in the values this
 * README shows: a backtick closes it, a newline ends the block it is in (a
 * multi-line SYSTEM_PROMPT used to shred the variables table and every row under
 * it), and a `|` splits a table row into extra cells. One helper, used everywhere
 * a value is rendered, rather than a different half-escape at each call site.
 */
function codeSpan(value: string): string {
  return value
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/`/g, "'")
    .replace(/\|/g, '\\|');
}

/**
 * The model, linked to its Hub page when the id is one the Hub could have.
 *
 * A Markdown link destination ends at the first `)`, so an id that is not a repo id
 * is shown as a code span and not linked at all — `isValidRepoId` allows only
 * `owner/name` out of word characters, dots and dashes, which is exactly the set
 * that survives a URL untouched.
 */
function modelReference(modelId: string, copy: ReadmeCopy): string {
  const shown = codeSpan(modelId);
  if (!shown) return copy.notSet;
  if (!isValidRepoId(modelId)) return `\`${shown}\``;
  return `[\`${shown}\`](https://huggingface.co/${modelId.trim()})`;
}

/**
 * The table of Space variables the owner can set without touching the code.
 *
 * `LANG` appears only on a Space that carries both languages, because that is the only
 * Space where it can do anything: a page baked in one language has no second set of
 * strings to switch to, and documenting a variable that cannot work is the paper
 * version of offering a button that cannot work.
 */
function variablesTable(config: SpaceConfigWithWeights, copy: ReadmeCopy): string {
  const rows: Array<[string, string, string]> = [
    ['`TITLE`', copy.varTitle, config.title],
    ['`MODEL_ID`', copy.varModel, config.modelId],
    ['`SYSTEM_PROMPT`', copy.varSystemPrompt, config.systemPrompt],
    ['`GREETING`', copy.varGreeting, config.greeting],
    ['`ACCENT`', copy.varAccent, config.accent],
  ];

  if (carriesBothLangs(config)) rows.push(['`LANG`', copy.varLang, '']);

  const body = rows
    .map(([name, purpose, current]) => {
      const value = codeSpan(current);
      return `| ${name} | ${purpose} | ${value ? `\`${value}\`` : copy.empty} |`;
    })
    .join('\n');

  return `${copy.tableHead}
| --- | --- | --- |
${body}`;
}

/**
 * The front matter plus the prose.
 *
 * The prose follows `config.lang`. `both` gets the CREATOR's language and one extra
 * line saying the page adapts to its visitor — a README is read by whoever inherits
 * the repository, and that is one person, not a worldwide audience; there is nothing
 * to gain from writing it twice.
 *
 * The front matter and the badge line are untouched by any of this. They are Hub
 * configuration and a URL, not words anybody reads.
 */
export function generateReadme(config: SpaceConfigWithWeights): string {
  const title = spaceHeading(config);
  const lang = bakedLang(config);
  const copy = README_COPY[lang];

  const frontMatter = [
    '---',
    `title: ${yamlString(title)}`,
    `emoji: ${yamlString(safeEmoji(config.emoji))}`,
    `colorFrom: ${safeColour(config.colorFrom, 'indigo')}`,
    `colorTo: ${safeColour(config.colorTo, 'purple')}`,
    'sdk: static',
    'pinned: false',
    '---',
  ];

  const badgeLine = config.badge
    ? `\n[![Made with Aparté Spaces](${SPACES_URL}/badge.svg)](${SPACES_URL})\n`
    : '';

  const bilingualLine = carriesBothLangs(config)
    ? `\n${fill(copy.bilingual, { fallback: copy.langNames[lang] })}\n`
    : '';

  return `${frontMatter.join('\n')}

# ${title}

${fill(copy.intro, { spaces: SPACES_URL })}

${fill(copy.summary, { model: modelReference(config.modelId, copy) })}
${bilingualLine}${badgeLine}
## ${copy.noAccountHeading}

${copy.noAccount}

${copy.gated}

## ${copy.changingHeading}

${copy.changing}

${variablesTable(config, copy)}

${copy.secrets}

### ${copy.downloadHeading}

${copy.download}

${copy.onnx}

## ${copy.contentsHeading}

${fill(copy.contents, { version: APARTE_VERSION })}

## ${copy.licenceHeading}

${copy.licence}
`;
}
