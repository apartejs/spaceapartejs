/**
 * The `README.md` of a generated Space.
 *
 * On Hugging Face the README is not documentation, it is configuration: the YAML
 * front matter is what tells the Hub this is a static Space and what to put on the
 * card. Get the front matter wrong and the Space does not build; the prose below it
 * is for the human who inherits the repo.
 *
 * V1 asks the Hub for NOTHING beyond a static build. No `hf_oauth`, no scopes, no
 * sign-in: the generated Space runs the model in the visitor's own browser, so it
 * needs no account, no token and costs nobody anything. (The configurator still
 * signs its user in — to read a private model and to push the Space — but none of
 * that reaches the artefact this file describes.)
 */

